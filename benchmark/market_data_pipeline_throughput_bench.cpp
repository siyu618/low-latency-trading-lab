// ---- canonical configuration ----------------------------------------------

// The two knobs that define the single Phase-3A cell. Constants, not options:
// see "ONE CANONICAL CELL" above.
constexpr std::size_t kChunkBytes = 64 * 1024; // 64 KiB source chunks
constexpr std::size_t kCapacity   = 4096;      // SPSC capacity

// ---- defaults -------------------------------------------------------------

constexpr std::uint64_t kDefaultLiveMessages = 5'000'000;
constexpr int           kDefaultReps         = 5;
constexpr int           kDefaultWarmup       = 1;
constexpr std::uint64_t kDefaultSeed         = 0x5EED'C0FF'EEULL;

// ---- workload shape -------------------------------------------------------

constexpr std::int64_t  kMid           = 100'000; // inside [1, 200000]
constexpr int           kLevelsPerSide = 64;
constexpr std::uint64_t kDeletePercent = 12;   // per-message delete probability
constexpr std::int64_t  kMaxQty        = 1000;
constexpr std::int64_t  kSnapshotQty   = 100;

// Phase 2's retry policy, reused verbatim. Consecutive misses, never a sleep.
constexpr std::uint64_t kYieldAfterMisses = 1024;

// The repository's shared unreachable-sink guard (splitmix64's golden gamma).
constexpr std::uint64_t kSinkGuard = 0x9E37'79B9'7F4A'7C15ULL;

// Exit vocabulary, matching the Phase-4 benchmark's convention.
constexpr int kExitOk              = 0;
constexpr int kExitUsage           = 2;
constexpr int kExitReferenceFailed = 3; // the pre-timing reference disagreed
constexpr int kExitMeasurementFail = 4; // a repetition failed its own invariants

