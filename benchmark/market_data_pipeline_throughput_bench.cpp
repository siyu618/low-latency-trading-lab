// ---------------------------------------------------------------------------
// Observable state, so that "the runs agree" is a statement about VALUES rather
// than about code paths.
// ---------------------------------------------------------------------------
struct Observation {
    MdState       state        = MdState::NotSynced;
    std::uint64_t last_applied = 0;
    std::uint64_t expected     = 0;
    std::int64_t  best_bid     = 0;
    std::int64_t  best_ask     = 0;
    std::size_t   level_count  = 0;
    MdCounters    counters{};
};

// FNV-1a over every observable. This is the deterministic sink the brief asks
// for: it cannot be computed unless the applies really happened, and it is
// compared against the reference and printed.
std::uint64_t fold_observation(const Observation& o) {
    std::uint64_t h = 0xCBF2'9CE4'8422'2325ULL;
    const auto mix = [&h](std::uint64_t v) {
        h ^= v;
        h *= 0x0000'0100'0000'01B3ULL;
    };
    mix(static_cast<std::uint64_t>(o.state));
    mix(o.last_applied);
    mix(o.expected);
    mix(static_cast<std::uint64_t>(o.best_bid));
    mix(static_cast<std::uint64_t>(o.best_ask));
    mix(static_cast<std::uint64_t>(o.level_count));
    mix(o.counters.messages);
    mix(o.counters.applied);
    mix(o.counters.out_of_range);
    mix(o.counters.staged);
    mix(o.counters.snapshot_committed);
    mix(o.counters.snapshot_abandoned);
    mix(o.counters.stale);
    mix(o.counters.gap_detected);
    mix(o.counters.malformed);
    mix(o.counters.rejected);
    mix(o.counters.protocol_violations);
    mix(o.counters.sync_attempts);
    mix(o.counters.stale_snapshot_begins);
    mix(o.counters.malformed_snapshots);
    mix(o.counters.empty_snapshots_committed);
    mix(o.counters.failed_initial_syncs);
    mix(o.counters.staging_limit_hits);
    mix(o.counters.nested_brackets_discarded);
    mix(o.counters.outages);
    mix(o.counters.recovered_outages);
    return h;
}

// ---------------------------------------------------------------------------
// The workload. Built once, entirely before any clock starts.
// ---------------------------------------------------------------------------
struct Workload {
    std::vector<MdMessage> messages;  // snapshot then live, in order
    std::vector<std::byte> wire;      // the encoded stream, byte-exact
    std::size_t   snapshot_messages = 0;
    std::size_t   snapshot_bytes    = 0;
    std::uint64_t live_messages     = 0;
    std::uint64_t sets              = 0;
    std::uint64_t deletes           = 0;
    std::uint64_t seed              = 0;
};

Workload build_workload(std::uint64_t live_messages, std::uint64_t seed) {
    Workload wl;
    wl.live_messages = live_messages;
    wl.seed          = seed;

    const std::size_t snapshot_messages =
        static_cast<std::size_t>(2 * kLevelsPerSide) + 2;
    wl.messages.reserve(static_cast<std::size_t>(live_messages) + snapshot_messages);

    // ---- the initial snapshot ---------------------------------------------
    std::uint64_t seq = 1;
    wl.messages.push_back(llmd::md_begin(seq++));
    for (int i = 0; i < kLevelsPerSide; ++i) {
        wl.messages.push_back(llmd::md_level(
            seq++, llob::Side::Bid, kMid - 1 - static_cast<std::int64_t>(i),
            kSnapshotQty + static_cast<std::int64_t>(i)));
    }
    for (int i = 0; i < kLevelsPerSide; ++i) {
        wl.messages.push_back(llmd::md_level(
            seq++, llob::Side::Ask, kMid + 1 + static_cast<std::int64_t>(i),
            kSnapshotQty + static_cast<std::int64_t>(i)));
    }
    wl.messages.push_back(llmd::md_end(seq++));
    wl.snapshot_messages = wl.messages.size();

    // ---- the live steady state --------------------------------------------
    llmd::gen::Rng rng(seed);
    for (std::uint64_t i = 0; i < live_messages; ++i) {
        const llob::Side side =
            (llmd::gen::uniform_below(rng, 2) != 0) ? llob::Side::Bid : llob::Side::Ask;
        const std::int64_t off = 1 + static_cast<std::int64_t>(
            llmd::gen::uniform_below(rng, static_cast<std::uint64_t>(kLevelsPerSide)));
        const std::int64_t px = (side == llob::Side::Bid) ? kMid - off : kMid + off;

        std::int64_t qty;
        if (llmd::gen::uniform_below(rng, 100) < kDeletePercent) {
            qty = 0;
            ++wl.deletes;
        } else {
            qty = 1 + static_cast<std::int64_t>(
                          llmd::gen::uniform_below(rng,
                                                   static_cast<std::uint64_t>(kMaxQty)));
            ++wl.sets;
        }
        wl.messages.push_back(llmd::md_level(seq++, side, px, qty));
    }

    // ---- encode ------------------------------------------------------------
    // The snapshot is encoded into its own byte range so the timed session can
    // feed exactly those bytes before the gate. Byte-exact, and the encoder is
    // the frozen Phase-1B one.
    for (std::size_t i = 0; i < wl.snapshot_messages; ++i) {
        llmd::encode::append_message(wl.wire, wl.messages[i]);
    }
    wl.snapshot_bytes = wl.wire.size();
    for (std::size_t i = wl.snapshot_messages; i < wl.messages.size(); ++i) {
        llmd::encode::append_message(wl.wire, wl.messages[i]);
    }
    return wl;
}

