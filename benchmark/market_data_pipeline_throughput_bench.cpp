// Experiment 03 Phase 3A — integrated market-data pipeline throughput baseline.
//
// ---------------------------------------------------------------------------
// RESEARCH QUESTION
// ---------------------------------------------------------------------------
//
// Phase 1A/1B verified the sequencer and the decoder single-threaded. Phase 2
// verified that the same correctness survives a thread boundary and a queue.
// Neither asked how FAST the composed path runs, because neither was allowed to
// read a clock. This tool reads one.
//
//   What steady-state end-to-end message throughput does the integrated
//   market-data path sustain under a deterministic valid live-update workload?
//
// The system under test is the composed path, in these exact stages:
//
//   pre-generated byte stream
//       -> StreamDecoder            (framing: chunk boundaries -> frames)
//       -> decode_one()             (frozen Phase-1B binary decode)
//       -> MdMessage
//       -> SpscSeparatedBaselineRingBuffer<MdMessage, 4096>
//       -> MarketDataPipeline<FlatOrderBook>   (sequencing + book apply)
//
// Every one of those components is FROZEN. This file integrates them; it does
// not modify them, and nothing here may be read as a claim that any of them was
// changed to improve a number.
//
// ---------------------------------------------------------------------------
// WHAT IS MEASURED — and what is not
// ---------------------------------------------------------------------------
//
// MEASURED, inside the timed interval:
//
//   stream framing, binary decode, message construction, queue handoff,
//   sequence validation, snapshot/staging bookkeeping, and FlatOrderBook apply
//
// NOT measured, deliberately kept outside the interval:
//
//   * synthetic workload generation, encoding, vector growth
//   * random-number generation
//   * the reference result and the expected checksum
//   * construction of the queue and the pipeline
//   * thread creation, thread wake-up, and the ready handshake
//   * the initial snapshot (see below)
//   * the join of either thread
//
// The number this tool prints is a THROUGHPUT in messages per second. It is NOT
// a latency, NOT a percentile, and NOT a per-message cost. Phase 3A measures
// throughput only; there is no clock read per message anywhere in this file,
// MdMessage carries no timestamp, and no side timestamp array exists. Per-message
// measurement is Phase 3B and is deliberately not started here.
//
// It is also NOT exchange throughput, NOT production trading throughput, and NOT
// wire-to-exchange anything. It is a synthetic integrated pipeline benchmark on
// one host under one fixed workload, and it is only comparable to another run of
// THIS tool with the SAME workload on the SAME host.
//
// ---------------------------------------------------------------------------
// ONE CANONICAL CELL — there is nothing to compare
// ---------------------------------------------------------------------------
//
// Phase 3A establishes ONE baseline. The chunk size and the queue capacity are
// COMPILE-TIME CONSTANTS here and are deliberately NOT command-line options: a
// flag would make a treatment matrix possible by accident, and §12 of the brief
// forbids treatment comparison in this phase. Cached vs baseline SPSC,
// SameLine vs Separated, Flat vs Map, other capacities and other chunk sizes are
// either already frozen experiments or future controlled factors. One cell.
//
//   canonical source chunk   64 KiB, final chunk naturally shorter
//   canonical queue capacity 4096
//
// Chunk-size sensitivity in particular is a separate experiment. Stating that
// the number includes framing under ONE chunk policy is part of the result, not
// a caveat bolted onto it: framing cost is a function of how the transport
// slices the stream.
//
// ---------------------------------------------------------------------------
// THE TIMED INTERVAL — exactly where it starts and stops
// ---------------------------------------------------------------------------
//
// Both worker threads are created first, and BOTH must be parked before the
// clock starts. This is the house handshake (see spsc_throughput_bench.cpp):
// each thread release-stores its own ready flag and then spins on `start`; the
// main thread waits for both flags, stamps t0, and release-stores `start`.
//
//   release start gate
//       -> producer consumes the first measured byte
//       -> framing / decode / push / pop / sequencing / apply
//       -> consumer applies the final measured message   <- t1, taken by the
//                                                           CONSUMER itself
//   then, and only then, main joins and computes elapsed = t1 - t0.
//
// t1 is taken by the consumer thread immediately after its final apply, NOT by
// the main thread after join(). Stopping after join would fold thread teardown
// and the join wake-up into every repetition; taking it after the producer
// finished decoding would stop before the book had done the work. Neither is
// this measurement.
//
// THE SNAPSHOT IS NOT IN THE TIMED INTERVAL. A small valid snapshot is required
// to bring the book to LIVE (the pipeline refuses live updates while unsynced),
// but recovery and sync paths are Phase 1/2 correctness territory and are
// excluded from a steady-state throughput figure by construction:
//
//   * the producer feeds ONLY the snapshot bytes, then parks on the gate
//   * the consumer drains EXACTLY the snapshot's messages, then parks
//   * main waits for both, so the book is already LIVE at t0
//   * every byte fed after the gate is a live Level update
//
// So messages_processed counts live updates only. The window contains no
// malformed bytes, no sequence gap, no stale message, no recovery snapshot, no
// terminal decode error and no truncated input — the workload cannot produce
// one, and the reference agreement check below would fail the run if it did.
//
// ---------------------------------------------------------------------------
// WORKLOAD
// ---------------------------------------------------------------------------
//
// Deterministic, seeded, generated entirely before the clock starts. A 64-level
// per side L2 book around mid 100000, then N live Level messages drawn from the
// same 128 price slots with a documented mix of sets and deletes. Prices stay
// inside FlatOrderBook's default [1, 200000] domain, so the run has zero
// out-of-range updates and the book never thins out: a deleted slot is re-drawn
// shortly after, which is what makes the steady state steady.
//
// This does NOT model any real exchange's message distribution. It is a
// reproducible workload chosen so that the composed path is exercised
// continuously at a stable level population.
//
// Randomness is llmd::gen::uniform_below (hand-rolled `rng() % n`), not
// std::uniform_int_distribution, whose mapping the standard leaves
// implementation-defined — the same rule md_stream_gen.h states for Experiment
// 03. The workload is pinned by a golden checksum, so it must reproduce
// byte-for-byte across standard libraries.
//
// ---------------------------------------------------------------------------
// VALIDATION — every run, timed or not
// ---------------------------------------------------------------------------
//
// A repetition that produced a wrong answer is not a slow repetition, it is
// not a measurement at all. Before any clock starts, this process:
//
//   1. decodes the whole stream with the frozen framer, requiring every chunk to
//      be Ok and the finalization to be Ok (no truncation, no malformed bytes);
//   2. computes a single-threaded reference by applying those messages to a
//      fresh MarketDataPipeline<FlatOrderBook>;
//   3. runs the FROZEN ThreadedMdPipeline over the same bytes and requires it to
//      agree with (2) on every observable and all twenty counters.
//
// Step 3 is what licenses the timed session below: this file owns its own two
// threads (it must, to place the gate and t1 where the brief requires), and the
// frozen Phase-2 harness is the oracle that proves those loop bodies behave
// identically to the validated composition. The timed runs are then required to
// match the same reference.
//
// Each measured repetition must satisfy ALL of:
//
//   terminal_error == false
//   decoded_messages == enqueued_messages == consumed_messages == total messages
//   consumed live messages == N
//   state, last_applied_seq, expected, best bid, best ask, level_count,
//   every counter, and the folded checksum all equal the reference
//
// A failing repetition is reported and the process exits non-zero. It is never
// quietly dropped to make the median look better.
//
// ---------------------------------------------------------------------------
// ANTI-DCE
// ---------------------------------------------------------------------------
//
// Every observable is folded into `sink`, `sink` is printed, and the checksum
// gates the process exit status. A fold over the final book state cannot be
// computed unless the applies really happened, and the exit contract makes the
// fold observable. There is no per-message fold: adding one would change the
// consumer loop being measured, and the loop under test is Phase 2's, unchanged.
//
// ---------------------------------------------------------------------------
// USAGE
// ---------------------------------------------------------------------------

